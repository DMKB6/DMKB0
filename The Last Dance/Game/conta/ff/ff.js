/* =========================================================
   GET HTML ELEMENTS
========================================================= */

const friendList = document.getElementById("friendList");
const searchInput = document.getElementById("searchInput");
const noResult = document.getElementById("noResult");
const modal = document.getElementById("detailsModal");


/* =========================================================
   DISPLAY FRIEND LIST
========================================================= */

function displayFriends(list) {

    friendList.innerHTML = "";

    /* No Result */

    if (list.length === 0) {

        noResult.style.display = "block";

        return;
    }

    noResult.style.display = "none";


    /* Create Friend Boxes */

    list.forEach((friend, index) => {

        const box = document.createElement("div");

        box.className = "friend-box";


        box.innerHTML = `

            <div class="friend-number">
                ${String(index + 1).padStart(2, "0")}
            </div>

            <img
                class="friend-img"
                src="${friend.image}"
                alt="${friend.name}"
            >

            <div class="friend-info">

                <div class="friend-name">
                    ${friend.name}
                </div>

                <div class="friend-uid">
                    UID: ${friend.uid}
                </div>

            </div>

            <div class="arrow">
                ›
            </div>

        `;


        /* Click Friend */

        box.addEventListener("click", function () {

            showDetails(friend);

        });


        friendList.appendChild(box);

    });

}


/* =========================================================
   SHOW PLAYER DETAILS
========================================================= */

function showDetails(friend) {

    document.getElementById("detailImage").src =
        friend.image;


    document.getElementById("detailImage").alt =
        friend.name;


    document.getElementById("detailName").textContent =
        friend.name;


    document.getElementById("detailUsername").textContent =
        friend.username;


    document.getElementById("detailUID").textContent =
        friend.uid;


    document.getElementById("detailLevel").textContent =
        friend.level;


    document.getElementById("detailLikes").textContent =
        friend.likes;


    document.getElementById("detailGuild").textContent =
        friend.guild;


    document.getElementById("detailRegion").textContent =
        friend.region;


    /* Open Modal */

    modal.classList.add("show");

}


/* =========================================================
   CLOSE PLAYER DETAILS
========================================================= */

function closeDetails() {

    modal.classList.remove("show");

}


/* =========================================================
   CLOSE MODAL BY CLICKING OUTSIDE
========================================================= */

modal.addEventListener("click", function (event) {

    if (event.target === modal) {

        closeDetails();

    }

});


/* =========================================================
   SEARCH FUNCTION
========================================================= */

searchInput.addEventListener("input", function () {

    const searchText = this.value
        .toLowerCase()
        .trim();


    const filteredFriends = friends.filter(function (friend) {

        return (

            friend.name
                .toLowerCase()
                .includes(searchText)

            ||

            friend.username
                .toLowerCase()
                .includes(searchText)

            ||

            friend.uid
                .includes(searchText)

            ||

            friend.guild
                .toLowerCase()
                .includes(searchText)

            ||

            friend.region
                .toLowerCase()
                .includes(searchText)

        );

    });


    displayFriends(filteredFriends);

});


/* =========================================================
   ESC KEY = CLOSE MODAL
========================================================= */

document.addEventListener("keydown", function (event) {

    if (event.key === "Escape") {

        closeDetails();

    }

});


/* =========================================================
   INITIAL LOAD
========================================================= */

displayFriends(friends);