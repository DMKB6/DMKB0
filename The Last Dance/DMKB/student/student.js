/* =====================================================
   BANGLADESH NUMBER
===================================================== */

function internationalNumber(number) {

    if (!number) return "";

    const clean =
        number.replace(/\D/g, "");

    if (
        clean.length === 11 &&
        clean.startsWith("01")
    ) {

        return "880" +
            clean.substring(1);
    }

    return clean;
}


/* =====================================================
   CALL / WHATSAPP / TELEGRAM
===================================================== */

function createButton(type, number) {

    if (!number) return "";


    /* Masked number */

    if (number.includes("*")) {

        return `
            <span class="contact-btn">
                <i class="fa-solid fa-lock"></i>
                ${type}
            </span>
        `;
    }


    const intl =
        internationalNumber(number);

    let link = "";
    let icon = "";
    let className = "";


    if (type === "Call") {

        link = `tel:${number}`;

        icon =
            "fa-solid fa-phone";

        className = "call";
    }


    if (type === "WhatsApp") {

        link =
            `https://wa.me/${intl}`;

        icon =
            "fa-brands fa-whatsapp";

        className = "whatsapp";
    }


    if (type === "Telegram") {

        link =
            `https://t.me/+${intl}`;

        icon =
            "fa-brands fa-telegram";

        className = "telegram";
    }


    return `
        <a
            class="contact-btn ${className}"
            href="${link}"
            target="_blank"
            rel="noopener noreferrer"
        >

            <i class="${icon}"></i>

            ${type}

        </a>
    `;
}


/* =====================================================
   SOCIAL BUTTON
===================================================== */

function createSocialButton(type, value) {

    if (!value) return "";


    let link = "";
    let icon = "";
    let className = "";


    /* FACEBOOK */

    if (type === "Facebook") {

        link = value;

        icon =
            "fa-brands fa-facebook";

        className = "facebook";
    }


    /* X */

    if (type === "X") {

        link = value;

        icon =
            "fa-brands fa-x-twitter";

        className = "x";
    }


    /* IMO */

    if (type === "IMO") {

        link =
            `https://imo.im/${value}`;

        icon =
            "fa-solid fa-comment";

        className = "imo";
    }


    /* INSTAGRAM */

    if (type === "Instagram") {

        link = value;

        icon =
            "fa-brands fa-instagram";

        className = "instagram";
    }


    /* TIKTOK */

    if (type === "TikTok") {

        link = value;

        icon =
            "fa-brands fa-tiktok";

        className = "tiktok";
    }


    return `
        <a
            class="contact-btn ${className}"
            href="${link}"
            target="_blank"
            rel="noopener noreferrer"
        >

            <i class="${icon}"></i>

            ${type}

        </a>
    `;
}


